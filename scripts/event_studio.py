"""Validate designer or model-authored event content and compile its Luau catalog."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "content/continental-cup.json"
GENERATED = ROOT / "src/shared/EventCards.luau"
ID = re.compile(r"[a-z][a-z0-9_]{2,39}\Z")
KINDS = {"transfer", "bonus", "penalty", "goal", "offside", "bench"}
SHOT_RESULTS = {"goal", "save", "offside"}


def require(ok, message):
    if not ok:
        raise ValueError(message)


def fields(value, keys, path):
    require(isinstance(value, dict) and set(value) == set(keys.split()), f"{path}: unexpected or missing fields")


def integer(value, lo, hi, path):
    require(type(value) is int and lo <= value <= hi, f"{path}: expected integer in [{lo}, {hi}]")


def localized(value, limit, path):
    require(isinstance(value, str) and 1 <= len(value.strip()) <= limit and not any(ord(c) < 32 or ord(c) == 127 for c in value),
            f"{path}: expected nonempty clear text up to {limit} characters")


def identifier(value, path):
    require(isinstance(value, str) and bool(ID.fullmatch(value)), f"{path}: invalid identifier")


def validate(edition):
    fields(edition, "schema_version id name ru trophy_value safe_cash shots cards", "event")
    integer(edition["schema_version"], 1, 1, "schema_version")
    identifier(edition["id"], "event.id")
    for key in ("name", "ru"):
        localized(edition[key], 44, key)
    integer(edition["trophy_value"], 40, 150, "trophy_value")
    integer(edition["safe_cash"], 45, 100, "safe_cash")
    shots = edition["shots"]
    require(isinstance(shots, list) and len(shots) == 3, "Expected three shot outcomes")
    seen = set()
    for slot, shot in enumerate(shots):
        fields(shot, "result cash weight", f"shots[{slot}]")
        r = shot["result"]
        require(isinstance(r, str) and r in SHOT_RESULTS and r not in seen, f"shots[{slot}]: unknown or duplicate outcome")
        integer(shot["weight"], 1, 9, f"{r}.weight")
        lo, hi = (-100, -1) if r == "offside" else (0, 200)
        integer(shot["cash"], lo, hi, f"{r}.cash")
        seen.add(r)
    weight = sum(s["weight"] for s in shots)
    goal = next(s for s in shots if s["result"] == "goal")
    require(len(seen) == len(SHOT_RESULTS) and 2 * goal["weight"] <= weight, "Goal chance must be at most 50%")
    mean = sum(s["weight"] * s["cash"] for s in shots) / weight
    require(mean <= edition["safe_cash"] <= mean + goal["weight"] * edition["trophy_value"] / weight,
            "Safe cash must sit between the shot's average cash and average portfolio value")
    cards = edition["cards"]
    require(isinstance(cards, list) and 6 <= len(cards) <= 20, "Expected 6–20 cards")
    seen = set()
    for index, card in enumerate(cards):
        path = f"cards[{index}]"
        fields(card, "id kind amount title ru body ruBody", path)
        identifier(card["id"], f"{path}.id")
        require(card["id"] not in seen, f"{path}: duplicate id")
        seen.add(card["id"])
        require(isinstance(card["kind"], str) and card["kind"] in KINDS, f"{path}: unknown kind")
        lo, hi = ((0, 0) if card["kind"] == "bench" else
                  (-100, -1) if card["kind"] in {"penalty", "offside"} else (0, 180))
        integer(card["amount"], lo, hi, f"{path}.amount")
        for key, limit in (("title", 42), ("ru", 42), ("body", 125), ("ruBody", 125)):
            localized(card[key], limit, f"{path}.{key}")
    require({"goal", "offside", "penalty"} <= {card["kind"] for card in cards}, "Deck must feature goal, offside and penalty cards")
    return {"cards": len(cards), "shot_expected_cash": round(mean, 3),
            "shot_expected_value": round(mean + goal["weight"] * edition["trophy_value"] / weight, 3)}


def load(path=SOURCE):
    data = json.loads(path.read_text())
    return data, validate(data)


def to_luau(value):
    if isinstance(value, str):
        return json.dumps(value.strip(), ensure_ascii=False)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, list):
        return "table.freeze({" + ", ".join(map(to_luau, value)) + "})"
    return "table.freeze({" + ", ".join(f"{key} = {to_luau(val)}" for key, val in value.items()) + "})"


def compile_catalog(edition):
    lines = ["--!strict", "-- Generated by scripts/event_studio.py. Edit the source JSON.", "return table.freeze({"]
    for key in ("schema_version", "id", "name", "ru", "trophy_value", "safe_cash"):
        lines.append(f"\t{key} = {to_luau(edition[key])},")
    for key in ("shots", "cards"):
        lines.append(f"\t{key} = table.freeze({{")
        lines.extend(f"\t\t{to_luau(row)}," for row in edition[key])
        lines.append("\t}),")
    lines.append("})\n")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("validate", "compile", "check", "prompt"))
    parser.add_argument("--input", type=Path, default=SOURCE)
    opts = parser.parse_args()
    try:
        edition, stats = load(opts.input)
        if opts.command == "prompt":
            print("Draft an original EN/RU football event as JSON matching this example. Do not use real names. "
                  "Preserve the schema and audit fairness: safe cash is at least expected shot cash and at most expected "
                  "shot portfolio value. Goal chance at most 50%. Include goal, offside and penalty cards. "
                  "Return bare JSON for event_studio.py validate, then submit the diff for review.\n\n"
                  + json.dumps(edition, ensure_ascii=False, indent=2))
            return
        expected = compile_catalog(edition)
        if opts.command == "compile":
            require(opts.input.resolve() == SOURCE, "Promote a reviewed draft to content/continental-cup.json before compiling")
            GENERATED.write_text(expected)
        if opts.command == "check":
            require(GENERATED.is_file() and GENERATED.read_text() == expected, "Generated Luau is stale. Run event_studio.py compile.")
        print(f"{edition['id']}: {json.dumps(stats, sort_keys=True)}")
    except (ValueError, OSError) as exc:
        print(f"Content rejected: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc


if __name__ == "__main__":
    main()
