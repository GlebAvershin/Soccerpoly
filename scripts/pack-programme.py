"""Build filtered board thumbnails and separate RGB artwork for the open dossier."""
import base64
import io
from pathlib import Path
import subprocess

from PIL import Image, ImageEnhance, ImageFilter, ImageOps

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "art/programme"
RESAMPLE = Image.Resampling.LANCZOS
SOURCE = (ART / "kit.svg").read_text()
CLUBS = {
    "spain": [("SEV","F1E8D5","C43D43","sleeve"),("ATM","BD3448","F1E9D7","stripes"),
              ("FCB","263B78","A73051","stripes"),("RMA","F4EFE2","B89A59","shoulder")],
    "england": [("ARS","C63B39","F6EBDB","sleeve"),("LIV","9C202F","EACF91","shoulder"),
                ("MCI","91BFD8","F6EDDD","shoulder"),("MUN","BA3033","252B39","cuffs")],
    "germany": [("B04","D44341","242D33","sash"),("RBL","F1E8DC","C63745","centre"),
                ("BVB","F2C939","212B32","sash"),("BAY","BD3544","ECE3D2","centre")],
    "italy": [("ACM","942C33","242A32","stripes"),("INT","294E9D","202B36","stripes"),
              ("JUV","292D32","EFE6D6","stripes"),("NAP","4D9EC4","F2E9DC","cuffs")],
    "france": [("OL","EDE5D5","AD3440","centre"),("OM","EDE7D8","5DA7C6","shoulder"),
               ("ASM","AC313C","F5EADB","sash"),("PSG","263C62","C54145","centre")],
}
PATTERNS = {
    "stripes": ''.join(f'<rect x="{x}" y="45" width="18" height="171"/>' for x in range(74,182,32)),
    "sash": '<path d="M25 184 L200 49 L213 76 L41 213Z"/>',
    "centre": '<path d="M116 46h25v171h-25z"/>',
    "sleeve": '<path d="M20 43h55l9 21-9 44-44 32zm216 0h-55l-9 21 9 44 44 32z"/>',
    "shoulder": '<path d="M37 87 L65 52 L107 40 L112 48 L74 62Z M219 87 L191 52 L149 40 L144 48 L182 62Z"/>',
    "cuffs": '<path d="M25 102 L56 126 L63 117 L32 94Z M231 102 L200 126 L193 117 L224 94Z"/>',
}

def jersey(primary, secondary, style):
    import resvg_py
    svg = SOURCE.replace("PRIMARY","#"+primary).replace("SECONDARY","#"+secondary).replace("PATTERN",PATTERNS[style])
    png = resvg_py.svg_to_bytes(svg_string=svg,width=768,height=768)
    return Image.open(io.BytesIO(png)).convert("RGBA").resize((256,256),RESAMPLE)

def pack(key, image):
    rgba = image.convert("RGBA").tobytes()
    compressed = subprocess.run(["zstd","-12","--content-size","-q","-c", "--stream-size="+str(len(rgba))],
                                input=rgba, capture_output=True, check=True).stdout
    data = base64.b64encode(compressed).decode()
    return f'{key}={{width={image.width},height={image.height},pixels="{data}"}},'

def panels():
    for source, keys in [("stadiums",[*CLUBS,"venue","kickoff","championship"]),
                         ("events",["chance","tax","tour","bench"])]:
        image=Image.open(ART/(source+".png")).convert("RGB")
        w,h=image.width//2,image.height//(len(keys)//2)
        for i,key in enumerate(keys):
            x,y=i%2*w,i//2*h
            panel=image.crop((x+4,y+4,x+w-4,y+h-4))
            yield key,ImageOps.fit(panel,(768,256),method=RESAMPLE)

def district():
    image = Image.open(ART/"stadium-district.png").convert("RGB").resize((1024,1024), RESAMPLE)
    night = Image.new("RGB", image.size, "#192C34")
    image = Image.blend(ImageEnhance.Color(image).enhance(.82), night, .22)
    # Feather the cropped city into the larger arena floor in ultrawide views.
    width = image.width
    rim = [min(1, min(x,width-1-x)/(width*.09)) for x in range(width)]
    mask = Image.new("L", image.size)
    mask.putdata([round(255*min(x,y)) for y in rim for x in rim])
    image = Image.composite(image, night, mask).quantize(colors=256)
    (ROOT/"src/client/DistrictPaint.luau").write_text(
        "--!strict\n-- Generated by scripts/pack-programme.py.\nreturn {\n"+pack("district",image)+"\n}\n")

def main():
    district()
    thumbs,backdrops,kits=[],[],[]
    for key,panel in panels():
        # Preserve the original linework for the dossier. Reduce fine texture
        # on the miniature, where a roof truss can be smaller than one pixel.
        background=ImageEnhance.Color(panel).enhance(.83)
        backdrops.append(pack(key,background))
        miniature=ImageEnhance.Contrast(background.filter(ImageFilter.GaussianBlur(1.4))).enhance(.85)
        # Give the kit an uncluttered mount and preserve the stadium silhouette
        # on the right. A horizontal fade also holds up on the narrow side cells.
        if key in CLUBS:
            mount=Image.new("RGB",miniature.size,"#29404B")
            ramp=Image.new("L",(miniature.width,1))
            ramp.putdata([round(226*max(0,1-x/(miniature.width*.72))**.7) for x in range(miniature.width)])
            miniature=Image.composite(mount,miniature,ramp.resize(miniature.size))
            for code,primary,secondary,style in CLUBS[key]:
                kits.append(pack(code,jersey(primary,secondary,style)))
        thumbs.append(pack(key,miniature.resize((384,144),RESAMPLE)))
    output = ["--!strict", "-- Generated by scripts/pack-programme.py.", "return {"]
    for name,rows in [("board",thumbs),("stadium",backdrops),("kit",kits)]:
        output.extend([name+"={",*rows,"},"])
    (ROOT/"src/client/ProgrammePaint.luau").write_text("\n".join(output)+"\n}\n")

if __name__=="__main__":
    main()
