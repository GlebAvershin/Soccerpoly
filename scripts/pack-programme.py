"""Pack the illustrated match programme as shared sRGB panels for local Roblox builds."""
import base64
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
import re
from PIL import ImageDraw, ImageFont

def enc(raw):
    return base64.b64encode(raw).decode("ascii")

def pack_line(key, panel, count=256):
    pic=panel.quantize(colors=count)
    return f'{key}={{width={panel.width},height={panel.height},palette="{enc(bytes(pic.getpalette()))}",pixels="{enc(pic.tobytes())}"}},'

# Custom souvenir shirts. Each pattern is clipped to the embroidered silhouette.
def club_programme(panel, code, colours):
    base = panel.copy()
    w,h = 124,136
    primary, secondary = ("#"+value for value in colours)
    shirt = Image.new("RGB",(w,h),primary)
    paint = ImageDraw.Draw(shirt)
    if code in {"ATM","FCB","ACM","INT","JUV"}:
        for x in range(3,w,25): paint.rectangle((x,0,x+11,h),fill=secondary)
    elif code in {"ASM","B04","BVB"}:
        paint.polygon([(0,20),(0,57),(124,131),(124,94)],fill=secondary)
    elif code in {"PSG","OL","RBL","BAY"}:
        paint.rectangle((53,0,71,h),fill=secondary)
    elif code in {"ARS","SEV"}:
        paint.polygon([(0,0),(33,0),(29,65),(0,65)],fill=secondary)
        paint.polygon([(124,0),(91,0),(95,65),(124,65)],fill=secondary)
    else:
        paint.line([(8,46),(32,21),(48,22)],fill=secondary,width=5)
        paint.line([(116,46),(92,21),(76,22)],fill=secondary,width=5)
    shape=[(40,10),(21,17),(2,45),(19,58),(30,46),(27,122),(97,122),(94,46),(105,58),(122,45),(103,17),(84,10),(74,7),(50,7)]
    mask=Image.new("L",(w,h))
    ImageDraw.Draw(mask).polygon(shape,fill=255)
    paint.line(shape+[shape[0]],fill="#223641",width=3)
    paint.line([(48,8),(61,19),(76,8)],fill=secondary,width=6)
    paint.polygon([(78,35),(87,35),(85,44),(82,46),(78,42)],fill=secondary)
    paint.line([(33,116),(90,116)],fill=secondary,width=2)
    stamp=Image.new("RGBA",(w,h))
    stamp.paste(shirt,(0,0),mask)
    stamp=stamp.rotate(-7,resample=Image.Resampling.BICUBIC,expand=True)
    base.paste(stamp,(103,9),stamp)
    return base

groups=[("SEV","ATM","FCB","RMA"),("ARS","LIV","MCI","MUN"),("B04","RBL","BVB","BAY"),
        ("ACM","INT","JUV","NAP"),("OL","OM","ASM","PSG")]
fabrics={c:(a,b) for c,a,b in re.findall(r'(\w+)=\{"([0-9A-F]{6})","([0-9A-F]{6})"\}',(root/"src/client/Programme.luau").read_text())}
lines = ["--!strict", "-- Generated by scripts/pack-programme.py.", "return {"]
for source, keys in [
    ("stadiums", ["spain","england","germany","italy","france","venue","kickoff","championship"]),
    ("events", ["chance","tax","tour","bench"]),
]:
    atlas = Image.open(root / f"art/programme/{source}.png").convert("RGB")
    w, h = atlas.width//2, atlas.height//(len(keys)//2)
    for i, key in enumerate(keys):
        x,y = i%2*w,i//2*h
        panel = atlas.crop((x+3,y+3,x+w-3,y+h-3)).resize((384,160), Image.Resampling.LANCZOS)
        if source=="stadiums" and i<5:
            for code in groups[i]:
                lines.append(pack_line(code,club_programme(panel,code,fabrics[code]).resize((288,120),Image.Resampling.LANCZOS)))
        else:
            lines.append(pack_line(key,panel))
(root/"src/client/ProgrammePaint.luau").write_text("\n".join(lines)+"\n}\n")

# Fixed ink strips keep the character height legible when Studio minifies a
# SurfaceGui. A shared bilingual plate also avoids per-cell image allocations.
names = re.findall(r'(\w+)=\{"([^"]+)","([^"]+)"\}', (root/"src/client/BoardLabels.luau").read_text())
font = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"
plate = Image.new("RGB",(512,64*(len(names)+1)), "#FAF1DD")
pen = ImageDraw.Draw(plate)
events = {"CH","BENCH","TOUR","KO","CUP","TAX"}
def name_strip(x,y,label,dark):
    ink,paper = ("#FFF0CA","#213542") if dark else ("#172D39","#FAF1DD")
    pen.rectangle((x,y,x+255,y+63),fill=paper)
    f = ImageFont.truetype(font,58)
    while f.getlength(label)>242:
        f=ImageFont.truetype(font,f.size-1)
    bounds=pen.textbbox((0,0),label,font=f)
    pen.text((x+128-(bounds[0]+bounds[2])/2,y+32-(bounds[1]+bounds[3])/2),label,font=f,fill=ink)
# Two compact pages to stay within Roblox's 1024-pixel image dimension.
rows = []
for j,(code,en,ru) in enumerate(names):
    for x,label in ((0,en),(256,ru)):
        name_strip(x,j*64,label,code in events)
    rows.append(f'{code}={j},')
chips=Image.new("RGB",(320,64),"#FAF1DD")
p=ImageDraw.Draw(chips)
for n in range(10):
    p.text((n*32+16,32),str(n),anchor="mm",font=ImageFont.truetype(font,48),fill="#263C48")
plates=[pack_line("page1",plate.crop((0,0,512,1024))),pack_line("page2",plate.crop((0,1024,512,len(names)*64))),pack_line("digits",chips)]
(root/"src/client/ProgrammeType.luau").write_text("--!strict\n-- Generated by scripts/pack-programme.py.\nreturn {\n"+'\n'.join(plates)+"\nrows={"+''.join(rows)+"}\n}\n")
