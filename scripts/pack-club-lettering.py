"""Typeset the longer mobile card captions into one transparent condensed ink sheet."""
import argparse
from pathlib import Path
import re
import runpy

from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--font", type=Path, default=Path(
    "/System/Library/Fonts/Supplemental/DIN Condensed Bold.ttf"))
args = parser.parse_args()
labels = (root / "src/client/BoardLabels.luau").read_text().split("local names = {", 1)[1].split("\n}", 1)[0]
names = sorted({word for word in re.findall(r'"([^"]+)"', labels) if len(word) >= 6})
font = ImageFont.truetype(str(args.font), 60)
atlas = Image.new("RGBA", (512, 36 * ((len(names)+1)//2)))
rects = []
for row, name in enumerate(names):
    mask = Image.new("L", (512, 96))
    ImageDraw.Draw(mask).text((1, 0), name, font=font, fill=255)
    mask = mask.crop(mask.getbbox())
    # Condense the cut slightly to leave a margin on both sides of the ticket.
    width = round(32 * mask.width / mask.height * .78)
    mask = mask.resize((width, 32), Image.Resampling.LANCZOS)
    ink = Image.new("RGBA", mask.size, "white")
    ink.putalpha(mask)
    x, y = row % 2 * 256 + 2, row // 2 * 36 + 2
    atlas.paste(ink, (x, y))
    rects.append(f'["{name}"]={{x={x},y={y},width={width}}}')
assert atlas.height <= 1024
pack = runpy.run_path(str(root / "scripts/pack-programme.py"))["pack"]
(root / "src/client/ClubLettering.luau").write_text(
    "--!strict\n-- Generated by scripts/pack-club-lettering.py.\nreturn {\n" +
    pack("sheet", atlas) + "\nwords={\n" + ",\n".join(rects) + "\n}}\n")
