"""Build an inset low-poly relief from Natural Earth land polygons."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("geojson", type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
rings = []
for feature in json.loads(args.geojson.read_text())["features"]:
    geometry = feature["geometry"]
    polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    for polygon in polygons:
        ring = polygon[0]
        xs, ys = zip(*ring)
        rings.append((min(xs), max(xs), min(ys), max(ys), ring))


def land(x, y):
    for lo, hi, bottom, top, ring in rings:
        if not (lo <= x <= hi and bottom <= y <= top):
            continue
        inside = False
        ax, ay = ring[-1]
        for bx, by in ring:
            if ((ay > y) != (by > y)) and x < (bx - ax) * (y - ay) / (by - ay) + ax:
                inside = not inside
            ax, ay = bx, by
        if inside:
            return True
    return False


cols, rows = 72, 30
spans = []
for row in range(rows):
    start = None
    for col in range(cols + 1):
        exists = col < cols and land(-180 + (col + 0.5) * 360 / cols, 83 - (row + 0.5) * 141 / rows)
        if exists and start is None:
            start = col
        if not exists and start is not None:
            spans.append(f"\t{{{row}, {start}, {col - start}}},")
            start = None
payload = "\n".join(spans)
(root / "src/server/MapData.luau").write_text(
    f"--!strict\n-- Made with Natural Earth (ne_110m_land); generated by scripts/make-map.py.\n"
    f"return {{columns = {cols}, rows = {rows}, spans = {{\n{payload}\n}}}}\n"
)
print(f"Generated {len(spans)} map spans")
