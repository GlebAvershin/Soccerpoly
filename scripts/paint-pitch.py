"""Paint the match turf in world units, filter its grass fibres, and pack the Roblox texture."""
import base64
from pathlib import Path
import subprocess

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
WIDTH, HEIGHT = 1024, 878
rng = np.random.default_rng(2304)


def soft_noise(cols, rows):
    grid = rng.integers(0, 256, (rows, cols), dtype=np.uint8)
    enlarged = Image.fromarray(grid).resize((WIDTH, HEIGHT), Image.Resampling.BICUBIC)
    return np.asarray(enlarged, dtype=np.float32) / 127.5 - 1


def paint():
    x, z = np.meshgrid((np.arange(WIDTH) + .5) * 84 / WIDTH - 42,
                       (np.arange(HEIGHT) + .5) * 72 / HEIGHT - 36)
    # Each outward pass sweeps slightly toward the wing. Individual grass blades
    # are low contrast so only the direction of the cut survives minification.
    phase = (x + .13 * (np.sqrt(z * z + 2.3) - 15)) * np.pi / 8.4
    cuts = np.tanh(7 * np.sin(phase))
    glow = np.exp(-.85 * ((x / 34) ** 2 + (z / 29) ** 2))
    growth = 2.2 * soft_noise(21, 18) + 1.6 * soft_noise(78, 61) + .8 * soft_noise(227, 172)
    # The perimeter is a single return pass. Its rounded corners and softened
    # shoulder follow the turn radius of a mower.
    qx, qz = np.abs(x) - 34.9, np.abs(z) - 28
    edge_distance = np.hypot(np.maximum(qx, 0), np.maximum(qz, 0)) + np.minimum(np.maximum(qx, qz), 0)
    border = np.clip((edge_distance - 6.0) / .75, 0, 1)
    shoulder = np.exp(-((edge_distance - 6.35) / .43) ** 2)
    tone = (1 - border) * (6.6 * cuts + 2.4 * np.sin(.5 * phase + .07 * z)) - 10 * border + 2.7 * shoulder
    tone += 9 * glow + growth
    colors = np.stack((38 + .93 * tone, 109 + 1.18 * tone, 76 + .85 * tone), axis=-1)
    # Softer vegetation at the keeper's line and on the two penalty spots.
    goal_wear = np.exp(-((np.abs(x) - 35.75) / 2.3) ** 2 - (z / 7.0) ** 2)
    spot_wear = np.exp(-((np.abs(x) - 29.5) / .95) ** 2 - (z / .85) ** 2)
    wear = np.clip(goal_wear * .43 + spot_wear * .45, 0, .65) * (.88 + .22 * soft_noise(103, 80))
    colors = colors * (1 - wear[..., None]) + np.array([151, 150, 98]) * wear[..., None]

    # Draw small tufts at double resolution, then low-pass before combining them.
    nap = Image.new("L", (WIDTH * 2, HEIGHT * 2), 128)
    nib = ImageDraw.Draw(nap)
    for _ in range(85000):
        u, v = rng.integers(0, WIDTH * 2), rng.integers(0, HEIGHT * 2)
        lean = 1 if cuts[v // 2, u // 2] > 0 else -1
        length = rng.integers(2, 7)
        nib.line((u, v, u + lean * length, v - rng.integers(1, 4)), fill=int(rng.integers(98, 159)), width=2)
    nap = nap.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS).filter(ImageFilter.GaussianBlur(.40))
    colors += (np.asarray(nap, dtype=np.float32)[..., None] - 128) * .18
    return Image.fromarray(np.clip(np.rint(colors), 0, 255).astype(np.uint8))


def main():
    rgba = paint().convert("RGBA").tobytes()
    packed = subprocess.run(["zstd", "-q", "-15", "-c"], input=rgba, stdout=subprocess.PIPE, check=True).stdout
    payload = base64.b64encode(packed).decode()
    target = ROOT / "src/client/TurfPaint.luau"
    target.write_text(f'--!strict\n-- Generated by scripts/paint-pitch.py.\nreturn {{width={WIDTH},height={HEIGHT},pixels="{payload}"}}\n')


if __name__ == "__main__":
    main()
